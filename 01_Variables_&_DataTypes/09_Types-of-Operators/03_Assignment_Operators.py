# Assignment Operators are used to assign values to variables. They are a combination of an arithmetic operator and the assignment operator (=). Here are some common assignment operators in Python:

# Operator	Description
# =	Assigns a value to a variable
# +=	Adds a value to the variable and assigns the result to the variable
# -=	Subtracts a value from the variable and assigns the result to the variable
# *=	Multiplies the variable by a value and assigns the result to the variable
# /=	Divides the variable by a value and assigns the result to the variable
# //=	Performs floor division on the variable by a value and assigns the result to the variable
# %=	Calculates the modulus of the variable by a value and assigns the result to the variable
# **=	Performs exponentiation on the variable by a value and assigns the result to the variable

# Example of Assignment Operators   
x = 10
print("Initial value of x: ", x)    

x += 5
print("After x += 5: ", x)

x -= 3
print("After x -= 3: ", x)

x *= 2
print("After x *= 2: ", x)

x /= 4
print("After x /= 4: ", x)

x //= 2
print("After x //= 2: ", x)

x %= 3
print("After x %= 3: ", x)

x **= 4
print("After x **= 4: ", x)

