# Relational Operators are used to compare two values. They return a boolean value (True or False) based on the comparison. The relational operators in Python are:

# Operator	Description
# ==	Equal to
# !=	Not equal to
# >	Greater than
# <	Less than
# >=	Greater than or equal to
# <=	Less than or equal to   

# Input two numbers from user and compare them using relational operators
num1 = int(input("Enter first number : "))
num2 = int(input("Enter second number : "))

print("num1 == num2 : ", num1 == num2)
print("num1 != num2 : ", num1 != num2)
print("num1 > num2 : ", num1 > num2)
print("num1 < num2 : ", num1 < num2)
print("num1 >= num2 : ", num1 >= num2)
print("num1 <= num2 : ", num1 <= num2)

