# Type Conversion in Python
# Type conversion is the process of converting one data type to another. In Python, there are several built-in functions that can be used for type conversion:

# int() - converts a value to an integer
# float() - converts a value to a floating-point number
# str() - converts a value to a string
# bool() - converts a value to a boolean

# Input a number from user and convert it to different data types
num = input("Enter a number : ")
print("String : ", num)
print("Integer : ", int(num))
print("Float : ", float(num))
print("Boolean : ", bool(num))

